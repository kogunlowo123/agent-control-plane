"""Ed25519 signing keys for the audit chain and policy bundles.

Private keys are mounted from the cloud secret manager; they are never
generated by Terraform and never written by the service. Ephemeral keys
exist only for development and tests and are refused in production by
configuration validation.
"""

from __future__ import annotations

import base64
import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


@dataclass(frozen=True)
class SigningKey:
    private: Ed25519PrivateKey
    key_id: str

    @classmethod
    def ephemeral(cls, purpose: str) -> SigningKey:
        key = Ed25519PrivateKey.generate()
        return cls(key, f"{purpose}-ephemeral-{_thumbprint(key.public_key())[:8]}")

    @classmethod
    def from_file(cls, path: Path) -> SigningKey:
        key = serialization.load_pem_private_key(path.read_bytes(), password=None)
        if not isinstance(key, Ed25519PrivateKey):
            raise ValueError(f"{path.name} is not an Ed25519 private key")
        return cls(key, path.stem)

    @property
    def public(self) -> Ed25519PublicKey:
        return self.private.public_key()

    def sign(self, data: bytes) -> bytes:
        return self.private.sign(data)

    def jwk(self) -> dict[str, Any]:
        raw = self.public.public_bytes(
            encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
        )
        return {"kty": "OKP", "crv": "Ed25519", "x": _b64url(raw), "kid": self.key_id, "use": "sig"}


def _thumbprint(public: Ed25519PublicKey) -> str:
    raw = public.public_bytes(
        encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
    )
    return hashlib.sha256(raw).hexdigest()


def sign_digest(key: SigningKey, digest: str) -> str:
    """Sign a ``sha256:<hex>`` digest; returns base64url signature."""
    return _b64url(key.sign(digest.encode()))


def verify_digest(public: Ed25519PublicKey, digest: str, signature: str) -> bool:
    padded = signature + "=" * (-len(signature) % 4)
    try:
        public.verify(base64.urlsafe_b64decode(padded), digest.encode())
    except (InvalidSignature, ValueError):
        return False
    return True
